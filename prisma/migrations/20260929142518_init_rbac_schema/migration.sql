BEGIN TRY

BEGIN TRAN;

CREATE TABLE [dbo].[Users] (
    [id] UNIQUEIDENTIFIER NOT NULL,
    [username] NVARCHAR(255) NOT NULL,
    [isActive] BIT NOT NULL DEFAULT 1,
    PRIMARY KEY CLUSTERED ([id]),
    UNIQUE NONCLUSTERED ([username])
);

CREATE TABLE [dbo].[Roles] (
    [id] INT NOT NULL IDENTITY(1,1),
    [name] NVARCHAR(100) NOT NULL,
    [description] NVARCHAR(500),
    [createdAt] DATETIME2 NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY CLUSTERED ([id]),
    UNIQUE NONCLUSTERED ([name])
);

CREATE TABLE [dbo].[Permissions] (
    [id] INT NOT NULL IDENTITY(1,1),
    [name] NVARCHAR(100) NOT NULL,
    [resource] NVARCHAR(100) NOT NULL,
    PRIMARY KEY CLUSTERED ([id]),
    UNIQUE NONCLUSTERED ([name])
);

CREATE TABLE [dbo].[UserRoles] (
    [userId] UNIQUEIDENTIFIER NOT NULL,
    [roleId] INT NOT NULL,
    PRIMARY KEY CLUSTERED ([userId], [roleId]),
    FOREIGN KEY ([userId]) REFERENCES [dbo].[Users]([id]) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY ([roleId]) REFERENCES [dbo].[Roles]([id]) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE [dbo].[RolePermissions] (
    [roleId] INT NOT NULL,
    [permissionId] INT NOT NULL,
    PRIMARY KEY CLUSTERED ([roleId], [permissionId]),
    FOREIGN KEY ([roleId]) REFERENCES [dbo].[Roles]([id]) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY ([permissionId]) REFERENCES [dbo].[Permissions]([id]) ON DELETE CASCADE ON UPDATE CASCADE
);

COMMIT TRAN;

END TRY
BEGIN CATCH

IF @@TRANCOUNT > 0
BEGIN
    ROLLBACK TRAN;
END;
THROW

END CATCH